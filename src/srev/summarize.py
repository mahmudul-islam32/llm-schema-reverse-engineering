"""Summarise repeated runs (different seeds) into mean ± standard deviation.

A single run already reports bootstrap CIs within that run; repeating the run
with different seeds (data generation, noise, sampling) shows how much the
conclusions depend on one particular draw. ``srev summarize RUN...`` reads
each run's ``aggregates.json`` and writes, per constraint type, a table of
variants × noise levels with the mean and sample standard deviation of macro
F1 (and micro P/R/F1 in the CSV), plus seed-averaged robustness charts and a
booktabs LaTeX version.
"""

from __future__ import annotations

import csv
import json
import math
from collections import defaultdict
from pathlib import Path
from typing import Any

from srev.export import escape
from srev.model import CONSTRAINT_TYPES
from srev.report import noise_curve_svg

METRICS = ("macro_f1", "micro_precision", "micro_recall", "micro_f1")


def _mean_sd(values: list[float]) -> tuple[float | None, float | None]:
    if not values:
        return None, None
    m = sum(values) / len(values)
    if len(values) < 2:
        return m, None
    return m, math.sqrt(sum((v - m) ** 2 for v in values) / (len(values) - 1))


def summarize(run_dirs: list[str | Path]) -> list[dict[str, Any]]:
    groups: dict[tuple[str, str, str], dict[str, list[float]]] = defaultdict(
        lambda: defaultdict(list)
    )
    order: dict[tuple[str, str, str], int] = {}
    for rd in run_dirs:
        for agg in json.loads((Path(rd) / "aggregates.json").read_text()):
            key = (agg["type"], agg["variant"], agg["noise"])
            order.setdefault(key, len(order))
            for m in METRICS:
                if agg.get(m) is not None:
                    groups[key][m].append(agg[m])
    # drop (type, variant) pairs that never produce a value, e.g. the FK-only learned model
    # in the UCC and FD tables
    defined = {(t, v) for (t, v, _), metrics in groups.items() if metrics.get("macro_f1")}
    out = []
    for key in sorted(groups, key=order.__getitem__):
        if (key[0], key[1]) not in defined:
            continue
        ctype, variant, noise = key
        row: dict[str, Any] = {"type": ctype, "variant": variant, "noise": noise,
                               "runs": len(run_dirs)}  # fmt: skip
        for m in METRICS:
            mean, sd = _mean_sd(groups[key][m])
            row[f"{m}_mean"] = None if mean is None else round(mean, 4)
            row[f"{m}_sd"] = None if sd is None else round(sd, 4)
            row[f"{m}_n"] = len(groups[key][m])
        out.append(row)
    return out


def _cell(mean: float | None, sd: float | None) -> str:
    if mean is None:
        return "–"
    return f"{mean:.2f}" if sd is None else f"{mean:.2f} ± {sd:.2f}"


def to_markdown(rows: list[dict[str, Any]], run_dirs: list[str | Path]) -> str:
    noise = list(dict.fromkeys(r["noise"] for r in rows))
    lines = [
        "# Benchmark summary",
        "",
        f"Macro F1 (mean ± sample sd over {len(run_dirs)} runs: "
        + ", ".join(Path(r).name for r in run_dirs)
        + "). Each run averages over its databases; '–' means undefined (no proposals or no gold).",
        "",
    ]
    for ctype in CONSTRAINT_TYPES:
        typed = [r for r in rows if r["type"] == ctype]
        if not typed:
            continue
        cells: dict[str, dict[str, str]] = defaultdict(dict)
        for r in typed:
            cells[r["variant"]][r["noise"]] = _cell(r["macro_f1_mean"], r["macro_f1_sd"])
        lines += [f"## {ctype}", "", "| variant | " + " | ".join(noise) + " |",
                  "|---|" + "---|" * len(noise)]  # fmt: skip
        lines += [f"| {v} | " + " | ".join(c.get(n, "–") for n in noise) + " |"
                  for v, c in cells.items()]  # fmt: skip
        lines.append("")
    return "\n".join(lines)


def to_latex(rows: list[dict[str, Any]], variants: list[str] | None = None) -> str:
    noise = list(dict.fromkeys(r["noise"] for r in rows))
    out = [r"% Generated by srev summarize; requires \usepackage{booktabs}."]
    for ctype in CONSTRAINT_TYPES:
        typed = [
            r for r in rows if r["type"] == ctype and (not variants or r["variant"] in variants)
        ]
        if not typed:
            continue
        best = {
            n: max((r["macro_f1_mean"] for r in typed if r["noise"] == n and r["macro_f1_mean"]
                    is not None), default=None)
            for n in noise
        }  # fmt: skip
        cells: dict[str, dict[str, str]] = defaultdict(dict)
        for r in typed:
            mean, sd = r["macro_f1_mean"], r["macro_f1_sd"]
            if mean is None:
                text = "--"
            else:
                text = f"{mean:.2f}" + (rf"{{\scriptsize$\pm${sd:.2f}}}" if sd is not None else "")
                if mean == best[r["noise"]]:
                    text = rf"\textbf{{{text}}}"
            cells[r["variant"]][r["noise"]] = text
        order = variants or list(cells)
        out += [
            "", r"\begin{table}[t]", r"  \centering", r"  \scriptsize",
            rf"  \caption{{{ctype} discovery: macro F1, mean $\pm$ sd over seeds.}}",
            rf"  \label{{tab:bench-{ctype.lower()}}}",
            rf"  \begin{{tabular}}{{l{'r' * len(noise)}}}", r"    \toprule",
            "    Method & " + " & ".join(escape(n) for n in noise) + r" \\", r"    \midrule",
        ]  # fmt: skip
        out += [f"    {escape(v)} & " + " & ".join(cells[v].get(n, "--") for n in noise) + r" \\"
                for v in order if v in cells]  # fmt: skip
        out += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]
    return "\n".join(out) + "\n"


def write(run_dirs: list[str | Path], out_dir: str | Path) -> list[Path]:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    rows = summarize(run_dirs)
    (out / "summary.json").write_text(json.dumps(rows, indent=2))
    with (out / "summary.csv").open("w", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    (out / "summary.md").write_text(to_markdown(rows, run_dirs))
    (out / "summary.tex").write_text(to_latex(rows))
    files = [out / f for f in ("summary.json", "summary.csv", "summary.md", "summary.tex")]
    levels = [n for n in dict.fromkeys(r["noise"] for r in rows) if not n.startswith("names-")]
    pseudo = [{"type": r["type"], "variant": r["variant"], "noise": r["noise"],
               "macro_f1": r["macro_f1_mean"]} for r in rows]  # fmt: skip
    for ctype in CONSTRAINT_TYPES:
        svg = noise_curve_svg(pseudo, ctype, levels)
        if svg:
            path = out / f"noise_curve_{ctype.lower()}.svg"
            path.write_text(svg.replace("macro F1 by noise level", "macro F1 by noise level "
                                        f"(mean of {len(run_dirs)} seeds)"))  # fmt: skip
            files.append(path)
    return files
