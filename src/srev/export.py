"""Paper-ready exports of stored run results (F-17).

``srev export latex RUN_DIR`` turns ``aggregates.json`` into one booktabs
table per constraint type: variants as rows, noise levels and name probes as
columns, the chosen metric in the cells, the best value per column in bold.
Requires ``\\usepackage{booktabs}`` in the document.
"""

from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path
from typing import Any

from srev.model import CONSTRAINT_TYPES

METRICS = ("macro_f1", "micro_f1", "micro_precision", "micro_recall")
_ESC = {"\\": r"\textbackslash{}", "_": r"\_", "%": r"\%", "&": r"\&", "#": r"\#",
        "$": r"\$", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\^{}"}  # fmt: skip


def escape(text: str) -> str:
    return "".join(_ESC.get(ch, ch) for ch in text)


def _cell(value: float | None, ci: Any, bold: bool, with_ci: bool) -> str:
    if value is None:
        return "--"
    body = f"{value:.2f}"
    if bold:
        body = rf"\textbf{{{body}}}"
    if with_ci and ci:
        body += rf"\,{{\scriptsize[{ci[0]:.2f}, {ci[1]:.2f}]}}"
    return body


def latex_tables(
    run_dir: str | Path,
    *,
    metric: str = "macro_f1",
    types: tuple[str, ...] = CONSTRAINT_TYPES,
    variants: list[str] | None = None,
    with_ci: bool = False,
) -> str:
    if metric not in METRICS:
        raise ValueError(f"metric must be one of {METRICS}")
    rows: list[dict[str, Any]] = json.loads((Path(run_dir) / "aggregates.json").read_text())
    noise = list(dict.fromkeys(r["noise"] for r in rows))
    run_name = Path(run_dir).name
    out = [
        f"% Generated by srev from {escape(run_name)}; metric: {metric}.",
        r"% Requires \usepackage{booktabs}.",
    ]
    for ctype in types:
        cells: dict[str, dict[str, tuple[float | None, Any]]] = defaultdict(dict)
        for r in rows:
            if r["type"] == ctype and (variants is None or r["variant"] in variants):
                ci = r.get("ci_macro_f1") if metric == "macro_f1" else None
                cells[r["variant"]][r["noise"]] = (r[metric], ci)
        if not cells:
            continue
        best: dict[str, float | None] = {}
        for n in noise:
            present = [v[n][0] for v in cells.values() if n in v and v[n][0] is not None]
            best[n] = max(present) if present else None  # type: ignore[type-var]
        order = variants or list(cells)
        label = metric.replace("_", " ").replace("f1", "F1")
        out += [
            "",
            r"\begin{table}[t]",
            r"  \centering",
            r"  \small",
            rf"  \caption{{{ctype} discovery: {label} by noise level. "
            r"Best value per column in bold.}",
            rf"  \label{{tab:srev-{ctype.lower()}}}",
            rf"  \begin{{tabular}}{{l{'r' * len(noise)}}}",
            r"    \toprule",
            "    Method & " + " & ".join(escape(n) for n in noise) + r" \\",
            r"    \midrule",
        ]
        for v in order:
            if v not in cells:
                continue
            vals = [
                _cell(
                    cells[v].get(n, (None, None))[0],
                    cells[v].get(n, (None, None))[1],
                    cells[v].get(n, (None, None))[0] is not None and cells[v][n][0] == best[n],
                    with_ci,
                )
                for n in noise
            ]
            out.append(f"    {escape(v)} & " + " & ".join(vals) + r" \\")
        out += [r"    \bottomrule", r"  \end{tabular}", r"\end{table}"]
    return "\n".join(out) + "\n"
